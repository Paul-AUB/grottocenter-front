def apply_translations(lang_code, trans_dict):
    path = os.path.join(LANG_DIR, f'{lang_code}.json')
    with open(path, encoding='utf-8') as f:
        data = json.load(f)
    with open(os.path.join(LANG_DIR, 'en.json'), encoding='utf-8') as f:
        en = json.load(f)
    count = 0
    for key, langs in trans_dict.items():
        if key not in en:
            continue
        if lang_code in langs:
            val = langs[lang_code]
            if key not in data or data[key] == en[key]:
                data[key] = val
                count += 1
    sorted_data = dict(sorted(data.items()))
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(sorted_data, f, ensure_ascii=False, indent=2)
    return count

