def load_json(path):
    with open(path, encoding='utf-8') as f:
        return json.load(f)


def save_json(path, data):
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2, sort_keys=True)
        f.write('\n')


def apply_translations():
    en = load_json(os.path.join(LANG_DIR, 'en.json'))
    stats = {}

    langs = ['fr', 'es', 'it', 'pt', 'de', 'nl', 'ca', 'ro', 'bg', 'el', 'ar', 'he', 'id', 'ja']
    for lang in langs:
        path = os.path.join(LANG_DIR, f'{lang}.json')
        data = load_json(path)
        count = 0
        for key, translations in TRANSLATIONS.items():
            if lang in translations:
                new_val = translations[lang]
                old_val = data.get(key, '')
                # Only update if currently missing or same as English
                if old_val == '' or old_val == en.get(key, ''):
                    data[key] = new_val
                    count += 1
        save_json(path, data)
        stats[lang] = count

    for lang, count in stats.items():
        print(f'{lang}: applied {count} translations')


if __name__ == '__main__':
    apply_translations()
